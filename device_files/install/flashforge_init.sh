#!/bin/sh
set -ex

# workdir contains our update files
cd "$(dirname "$0")"
WORK_DIR="$(pwd)"
MACHINE=$1
PID=$2
INSTALL_MEDIA_MOUNTED=0

# error handling
error_handler() {
  xzcat $WORK_DIR/img/install_fail_error.img.xz > /dev/fb0
  sync
  # always exit without error, to prevent immediate boot of flashforge software
  exit 0
}
trap '[ $? -eq 0 ] && exit 0 || error_handler' EXIT

do_setup()
{
    # safety check, only install on supported printer
    if ([ "$MACHINE" != "Adventurer5M" ] && [ "$MACHINE" != "Adventurer5MPro" ]) || \
       ([ "$PID" != "0023" ] && [ "$PID" != "0024" ]) || \
        [ "$(uname -m)" != "armv7l" ]
     then
        echo "Update file does not match machine type."
        xzcat $WORK_DIR/img/install_fail_vers.img.xz > /dev/fb0
        exit 0
    fi

    # saftey check, only install on supported versions
    FF_VERSION="$(cat /root/version)"
    MIN_VERSION="2.4.5"
    if [ "${FF_VERSION//./}" -lt "${MIN_VERSION//./}" ]
    then
        echo "Printer software version not supported."
        xzcat $WORK_DIR/img/install_fail_vers.img.xz > /dev/fb0
        exit 0
    fi

    MOD_INIT_FILE="/etc/init.d/S00klipper_mod"
    MOD_INIT_FILE_OLD="/etc/init.d/S90klipper_mod"
    MOD_DIR="/data/.klipper_mod"
    # chroot is replaced on mod upate or reinstall
    # other data in .klipper_mod is kept, unless uninstalled
    CHROOT_DIR="${MOD_DIR}/chroot"

    # update start image
    xzcat $WORK_DIR/img/install_start.img.xz > /dev/fb0
    # --------------------------------

    # Check the complete compressed payload before changing an existing install.
    # This is deliberately a preflight only: AD5M-019 owns transactional
    # staging/rollback and release-authenticity verification.
    if ! xz -t "$WORK_DIR/chroot.tar.xz"; then
        echo "Invalid chroot archive. Existing installation was not changed."
        exit 1
    fi
    if ! xz -dc "$WORK_DIR/chroot.tar.xz" | tar -tf - > /dev/null; then
        echo "Invalid chroot tar payload. Existing installation was not changed."
        exit 1
    fi

    # Check free space before removing the existing chroot.  This is more
    # conservative than the legacy flow: an update that cannot satisfy this
    # threshold now fails safely instead of first deleting its fallback.
    FREE_SPACE=$(df /data | tail -1 | tr -s ' ' | cut -d' ' -f4)
    MIN_SPACE="524228"
    if [ "$FREE_SPACE" -lt "$MIN_SPACE" ]
    then
        echo "Not enough free space on data partition. 512MB required!";
        xzcat $WORK_DIR/img/install_fail_mem.img.xz > /dev/fb0
        exit 0
    fi

    # replace previous mod version if present - keep other data in .klipper_mod
    rm -f $MOD_INIT_FILE
    rm -f $MOD_INIT_FILE_OLD
    rm -rf $CHROOT_DIR

    # calculate checksums to be printed in the log
    if ls /mnt/Adventurer5M*; then
      md5sum /mnt/Adventurer5M*
    fi
    md5sum $WORK_DIR/chroot.tar.xz

    # unpack chroot environment
    mkdir -p $CHROOT_DIR
    xz -dc $WORK_DIR/chroot.tar.xz | tar -xf - -C $CHROOT_DIR
    sync

    # do intial setup
    $CHROOT_DIR/etc/init/S00klipper_mod setup
    sync

    # Give the owner a simple, non-secret discovery record on the same USB
    # medium used for installation.  The persistent hostname is generated by
    # the chroot setup on a fresh install and retained on later updates.
    DEVICE_NAME_FILE="$MOD_DIR/static/etc/hostname"
    if [ "$INSTALL_MEDIA_MOUNTED" = "1" ] && [ -r "$DEVICE_NAME_FILE" ]; then
      DEVICE_NAME=$(tr -d '\r\n' < "$DEVICE_NAME_FILE")
      if "$CHROOT_DIR/usr/libexec/ad5m-device-name" validate "$DEVICE_NAME"; then
        {
          printf '%s\n' 'AD5M local-network addresses'
          printf '%s\n' "Hostname: $DEVICE_NAME.local"
          printf '%s\n' "Browser UI: http://$DEVICE_NAME.local:4000/"
          printf '%s\n' "Moonraker / slicer: http://$DEVICE_NAME.local:7125/"
          printf '%s\n' "Camera (when connected): http://$DEVICE_NAME.local:8080/stream"
          printf '%s\n' ''
          printf '%s\n' 'These addresses require local-network mDNS support after the printer has booted.'
        } > /mnt/AD5M-ADDRESS.txt
      else
        echo "Warning: no valid persistent hostname was available for AD5M-ADDRESS.txt"
      fi
    fi

    # install initfile
    cp $CHROOT_DIR/etc/init/S00klipper_mod /etc/init.d/
    sync

    # update end image
    # --------------------------------
    xzcat $WORK_DIR/img/install_ok.img.xz > /dev/fb0
}

# write log (if mount point is found)
if grep "^/dev/sd[ab12]* /mnt " /proc/mounts; then
  INSTALL_MEDIA_MOUNTED=1
  do_setup &> /mnt/klipper_mod_install.log
  sync
else
  do_setup
fi

exit 0
